        function indexMap(L, cols, rows) {
          var E = C.effect,
            n = L.length,
            t = new Float32Array(n),
            i
          for (i = 0; i < n; i++) t[i] = (1 - L[i]) * (N - 1)
          var idx = new Uint8Array(n)
          if (E.type === 'threshold') {
            var off = (0.5 - E.threshold) * 2 * (N - 1)
            for (i = 0; i < n; i++)
              idx[i] = clamp(Math.round(t[i] + off), 0, N - 1)
            return idx
          }
          if (E.type === 'ordered') {
            var st = E.strength
            if (E.pattern === 'noise') {
              var rnd = mulberry(E.seed * 9176 + 1)
              for (i = 0; i < n; i++) {
                var b0 = Math.floor(t[i]),
                  f0 = t[i] - b0,
                  th0 = 0.5 + (rnd() - 0.5) * st
                idx[i] = clamp(f0 > th0 ? b0 + 1 : b0, 0, N - 1)
              }
              return idx
            }
            var m = MAT.n,
              arr = MAT.arr,
              ox = E.pattern === 'bayer' ? 0 : E.seed % m
            for (var y = 0; y < rows; y++) {
              var my = (y % m) * m
              for (var x = 0; x < cols; x++) {
                var k = y * cols + x,
                  b = Math.floor(t[k]),
                  f = t[k] - b
                var th = 0.5 + (arr[my + ((x + ox) % m)] - 0.5) * st
                idx[k] = clamp(f > th ? b + 1 : b, 0, N - 1)
              }
            }
            return idx
          }
          var sd = E.strength
          var KER =
            E.type === 'atkinson'
              ? [
                  [1, 0, 1 / 8],
                  [2, 0, 1 / 8],
                  [-1, 1, 1 / 8],
                  [0, 1, 1 / 8],
                  [1, 1, 1 / 8],
                  [0, 2, 1 / 8],
                ]
              : [
                  [1, 0, 7 / 16],
                  [-1, 1, 3 / 16],
                  [0, 1, 5 / 16],
                  [1, 1, 1 / 16],
                ]
          for (var yy = 0; yy < rows; yy++) {
            var rev = E.serpentine && yy & 1
            for (var kk = 0; kk < cols; kk++) {
              var xx = rev ? cols - 1 - kk : kk,
                ii = yy * cols + xx
              var old = t[ii],
                q = clamp(Math.round(old), 0, N - 1)
              idx[ii] = q
              var err = (old - q) * sd
              if (!err) continue
              for (var jj = 0; jj < KER.length; jj++) {
                var ddx = rev ? -KER[jj][0] : KER[jj][0],
                  ddy = KER[jj][1],
                  ww = KER[jj][2]
                var nx2 = xx + ddx,
                  ny2 = yy + ddy
                if (nx2 < 0 || nx2 >= cols || ny2 >= rows) continue
                t[ny2 * cols + nx2] += err * ww
              }
            }
          }
          return idx
        }

