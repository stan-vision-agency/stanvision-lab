        /* The Vignette's texture. Same as vignetteTexture in main.ts, which has
     the explanation: noise that tiles along the streak so it can travel and
     still loop. */
        function hash2(x, y) {
          var n = (x * 374761393 + y * 668265263) | 0
          n = Math.imul(n ^ (n >>> 13), 1274126177)
          return ((n ^ (n >>> 16)) >>> 0) / 4294967296
        }
        function tileNoise(x, y, P) {
          var xi = Math.floor(x),
            yi = Math.floor(y),
            xf = x - xi,
            yf = y - yi
          var x0 = ((xi % P) + P) % P,
            x1 = (x0 + 1) % P
          var u = xf * xf * (3 - 2 * xf),
            v = yf * yf * (3 - 2 * yf)
          var a = hash2(x0, yi),
            b = hash2(x1, yi),
            c = hash2(x0, yi + 1),
            d = hash2(x1, yi + 1)
          return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v
        }
        function tileFbm(x, y, P, oct) {
          var sum = 0,
            amp = 0.5,
            norm = 0
          for (var k = 0; k < oct; k++) {
            sum += amp * tileNoise(x, y, P)
            norm += amp
            x *= 2
            y = y * 2.03 + 3.7
            P *= 2
            amp *= 0.5
          }
          return sum / norm
        }
        function vigTexture(look, dx, dy, sc, flow, twist) {
          if (look === 'swirl') {
            var r = Math.hypot(dx, dy) / sc,
              u = Math.atan2(dy, dx) / (Math.PI * 2)
            u += r * (0.35 + 0.12 * Math.sin(twist))
            var w = tileFbm(u * 5 + flow, r * 2.5 + 9, 5, 3) - 0.5,
              w2 = tileFbm(u * 9 - flow * 2, r * 3.5 + 2, 9, 2) - 0.5
            var Rr = r + w * 0.4
            u += w2 * 0.12
            var bd = tileFbm(u * 7 + flow * 2, Rr * 4.5, 7, 4),
              ct = tileFbm(u * 11 - flow * 3, Rr * 7 + 5, 11, 3)
            var fb =
              1 - Math.abs(2 * tileFbm(u * 14 + flow * 4, Rr * 13, 14, 3) - 1)
            fb = fb * fb
            var pt = ss((bd * 0.65 + ct * 0.35 - 0.36) / 0.24)
            return clamp(pt * (0.6 + 0.5 * fb) + 0.15 * pt * pt, 0, 1)
          }
          var a = ((dx - dy) * 0.70710678) / sc,
            s = ((dx + dy) * 0.70710678) / sc
          var S =
            s + (tileFbm(a * 1.2 + flow * 4, s * 1.2 + 9, 4, 3) - 0.5) * 0.3
          var body = tileFbm(a * 0.8 + flow * 4, S * 5, 4, 4)
          var fib =
            1 - Math.abs(2 * tileFbm(a * 1.4 + flow * 8, S * 22, 8, 3) - 1)
          fib = fib * fib * fib
          var patch = ss((body - 0.4) / 0.22)
          return clamp(patch * (0.25 + 1.1 * fib) + 0.15 * patch * patch, 0, 1)
        }

