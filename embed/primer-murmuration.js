          P.nullKeyframes = DEFAULTS.nullKeyframes.map((k) => ({ ...k })) // detach from DEFAULTS -- never share the array
        /* Every random draw goes through rand. Normally that is Math.random; with
     P.repeatable it is reseeded on every fresh start, so two runs from zero
     produce the same flock -- which is what lets a loop close on itself. */
        let rand = Math.random
        function seeded(seed) {
          let a = seed >>> 0
          return function () {
            a = (a + 0x6d2b79f5) >>> 0
            let t = Math.imul(a ^ (a >>> 15), 1 | a)
            t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
            return ((t ^ (t >>> 14)) >>> 0) / 4294967296
          }
        }
        // ---------------- rng helpers (match the python prototype's distributions) ----------------
        function randNormal() {
          let u = 0,
            v = 0
          while (u === 0) u = rand()
          while (v === 0) v = rand()
          return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v)
        }
        function randGamma(shape) {
          if (shape < 1) {
            const u = rand()
            return randGamma(1 + shape) * Math.pow(u, 1 / shape)
          }
          const d = shape - 1 / 3,
            c = 1 / Math.sqrt(9 * d)
          while (true) {
            let x, v
            do {
              x = randNormal()
              v = 1 + c * x
            } while (v <= 0)
            v = v * v * v
            const u = rand()
            if (u < 1 - 0.0331 * x * x * x * x) return d * v
            if (Math.log(u) < 0.5 * x * x + d * (1 - v + Math.log(v)))
              return d * v
          }
        }
        function randBeta(a, b) {
          const x = randGamma(a),
            y = randGamma(b)
          return x / (x + y)
        }
        function randPower(a) {
          return Math.pow(rand(), 1 / a)
        }
        function randRange(a, b) {
          return a + rand() * (b - a)
        }
        function smoothstep(x) {
          x = Math.min(1, Math.max(0, x))
          return x * x * (3 - 2 * x)
        }
        function clamp01(x) {
          return Math.min(1, Math.max(0, x))
        }
        // ---------------- guide ribbon ----------------
        function guideCurve(t, time) {
          // A coherent harmonic series (integer multiples of one base frequency, pi)
          // instead of clashing/incommensurate frequencies -- this guarantees the
          // curve reads as one continuous, graceful undulation with no "kink",
          // while still layering in plenty of visible waviness via the higher harmonics.
          const y =
            0.52 +
            0.09 * P.ampMul * Math.sin(t * Math.PI * 1 + 0.5 + time * 0.24) +
            0.042 * P.ampMul * Math.sin(t * Math.PI * 2 + 2.1 + time * 0.38) +
            0.02 * P.ampMul * Math.sin(t * Math.PI * 3 + 3.7 + time * 0.55) +
            0.01 * P.ampMul * Math.sin(t * Math.PI * 4 + 1.2 + time * 0.74)
          return [t, y]
        }
        function guideTangent(t, time) {
          // analytic derivative of guideCurve's y(t), term by term (d/dt[sin(k*pi*t+φ)]
          // = k*pi*cos(k*pi*t+φ)) -- mathematically what the old finite-difference
          // version was approximating with 2 extra guideCurve() calls per invocation,
          // which (called once per agent per physics step) was one of the hotter
          // spots in profiling. Numerically indistinguishable from the eps=1e-3
          // finite difference it replaces, at a third of the cost.
          const dy =
            0.09 *
              P.ampMul *
              Math.PI *
              1 *
              Math.cos(t * Math.PI * 1 + 0.5 + time * 0.24) +
            0.042 *
              P.ampMul *
              Math.PI *
              2 *
              Math.cos(t * Math.PI * 2 + 2.1 + time * 0.38) +
            0.02 *
              P.ampMul *
              Math.PI *
              3 *
              Math.cos(t * Math.PI * 3 + 3.7 + time * 0.55) +
            0.01 *
              P.ampMul *
              Math.PI *
              4 *
              Math.cos(t * Math.PI * 4 + 1.2 + time * 0.74)
          const n = Math.hypot(1, dy) + 1e-9
          return [1 / n, dy / n]
        }
        function curlNoise(time, x, y) {
          const xn = x / W,
            yn = y / H
          const fx =
            Math.sin(yn * 6.0 + time * 0.6) +
            Math.sin(yn * 2.3 - time * 0.35 + 1.7)
          const fy =
            Math.cos(xn * 6.0 - time * 0.5) +
            Math.cos(xn * 2.1 + time * 0.4 + 0.9)
          return [fx * 0.05 * P.turbulence, fy * 0.05 * P.turbulence]
        }
        // ---------------- energy oscillator: alternates calm / burst phases over time,
        // even with no user interaction, so cruising speed isn't perfectly constant ----------------
        let energyMode = 'rest',
          energyTimer = randRange(4, 9),
          energyMix = 0
        const REST_MIN = 4,
          REST_MAX = 9,
          ATTACK_MIN = 1.4,
          ATTACK_MAX = 3.2,
          ENERGY_TRANS_T = 1.15
        const REST_LEVEL = 0.55,
          ATTACK_LEVEL = 1.75

        function updateEnergy(dt) {
          energyTimer -= dt
          switch (energyMode) {
            case 'rest':
              if (energyTimer <= 0) {
                energyMode = 'toAttack'
                energyTimer = ENERGY_TRANS_T
              }
              break
            case 'toAttack':
              energyMix = smoothstep(1 - energyTimer / ENERGY_TRANS_T)
              if (energyTimer <= 0) {
                energyMode = 'attack'
                energyTimer = randRange(ATTACK_MIN, ATTACK_MAX)
                energyMix = 1
              }
              break
            case 'attack':
              if (energyTimer <= 0) {
                energyMode = 'toRest'
                energyTimer = ENERGY_TRANS_T
              }
              break
            case 'toRest':
              energyMix = smoothstep(energyTimer / ENERGY_TRANS_T)
              if (energyTimer <= 0) {
                energyMode = 'rest'
                energyTimer = randRange(REST_MIN, REST_MAX)
                energyMix = 0
              }
              break
          }
        }
        function energyFactor() {
          const base = REST_LEVEL + (ATTACK_LEVEL - REST_LEVEL) * energyMix // ~0.55..1.75
          return 1 + (base - 1) * P.energyVariation
        }
        // ---------------- state: main flock (three categories share one set of arrays) ----------------
        // layerCat: 0 = núcleo, 1 = cola, 2 = capa media (fuerza regulable vía P.midForce)
        const CAT_CORE = 0,
          CAT_TAIL = 1,
          CAT_MID = 2
        const GRAD_T_MIN = 0.15,
          GRAD_T_MAX = 0.92 // normalization range for the gradient coordinate
        const RIBBON_CENTER_T = 0.54 // pivot for ribbonLength scaling -- the center of the combined core/tail/mid t-range
        let N = 0,
          subPer = 0
        let tArr,
          layerCat,
          laneOffset,
          pos,
          vel,
          baseOffX,
          baseOffY,
          sizeJitter,
          phaseOffset,
          gradU
        let headDirX, headDirY
        let simTime = 0
        let alignX = new Float64Array(0),
          alignY = new Float64Array(0),
          sepX = new Float64Array(0),
          sepY = new Float64Array(0)
        let alignCount = new Int32Array(0),
          sepCount = new Int32Array(0)
        function regenerate() {
          const nCore = Math.round(P.nCore),
            nTail = Math.round(P.nTail),
            nMid = Math.round(P.nMid)
          N = nCore + nTail + nMid
          subPer = Math.round(P.subPer)

          tArr = new Float64Array(N)
          layerCat = new Uint8Array(N)
          laneOffset = new Float64Array(N)
          pos = new Float64Array(N * 2)
          vel = new Float64Array(N * 2)
          baseOffX = new Float64Array(N * subPer)
          baseOffY = new Float64Array(N * subPer)
          sizeJitter = new Float32Array(N * subPer)
          phaseOffset = new Float64Array(N)
          gradU = new Float64Array(N)
          headDirX = new Float64Array(N)
          headDirY = new Float64Array(N)

          // ribbonLength lengthens the ribbon by scaling each category's t-domain
          // outward from a fixed pivot at the middle of the combined range -- so a
          // longer ribbon naturally reveals MORE of the same continuous, non-repeating
          // guideCurve (more undulation) rather than stretching the existing shape thin.
          // clamped defensively so an out-of-range value (e.g. from an old/hand-edited preset)
          // can never push agents' base position off-canvas -- t maps directly to x/W
          const scaleT = (raw) =>
            Math.min(
              0.98,
              Math.max(
                0.02,
                RIBBON_CENTER_T + (raw - RIBBON_CENTER_T) * P.ribbonLength,
              ),
            )

          for (let i = 0; i < nCore; i++) {
            tArr[i] = scaleT(0.38 + 0.5 * randBeta(2.0, 1.6))
            layerCat[i] = CAT_CORE
          }
          for (let i = 0; i < nTail; i++) {
            const k = nCore + i
            tArr[k] = scaleT(0.4 - randPower(1.7) * 0.22)
            layerCat[k] = CAT_TAIL
          }
          for (let i = 0; i < nMid; i++) {
            const k = nCore + nTail + i
            tArr[k] = scaleT(0.34 + 0.56 * randBeta(1.6, 1.6)) // broader spread: a diffuse companion cloud along the whole ribbon
            layerCat[k] = CAT_MID
          }

          // lane-width tapering uses a 0..1 "progress" across each category's own span --
          // scale the bounds the same way so the taper shape stays correct at any ribbonLength
          const tailLo = scaleT(0.18),
            tailHi = scaleT(0.4)
          const midLo = scaleT(0.34),
            midHi = scaleT(0.9)
          const coreLo = scaleT(0.38),
            coreHi = scaleT(0.88)
          const gradLo = scaleT(GRAD_T_MIN),
            gradHi = scaleT(GRAD_T_MAX)

          for (let i = 0; i < N; i++) {
            const t = tArr[i]
            const cat = layerCat[i]
            let lane, spreadMul
            if (cat === CAT_TAIL) {
              lane = 0.045 + (0.075 * (tailHi - t)) / (tailHi - tailLo)
              spreadMul = 1.35
            } else if (cat === CAT_MID) {
              const midProgress = clamp01((t - midLo) / (midHi - midLo))
              lane = 0.05 + 0.05 * Math.sin(midProgress * Math.PI)
              spreadMul = 1.15
            } else {
              const coreProgress = clamp01((t - coreLo) / (coreHi - coreLo))
              lane = 0.045 + 0.028 * Math.sin(coreProgress * Math.PI)
              spreadMul = 1.0
            }
            lane *= P.ribbonWidth
            laneOffset[i] = randNormal() * lane
            gradU[i] = clamp01((t - gradLo) / (gradHi - gradLo))

            const [gx, gy] = guideCurve(t, 0)
            const [tx, ty] = guideTangent(t, 0)
            const nx = -ty,
              ny = tx
            pos[i * 2] = (gx + nx * laneOffset[i]) * W
            pos[i * 2 + 1] = (gy + ny * laneOffset[i]) * H
            vel[i * 2] = 0
            vel[i * 2 + 1] = 0
            phaseOffset[i] = rand() * 50
            headDirX[i] = tx
            headDirY[i] = ty

            for (let s = 0; s < subPer; s++) {
              baseOffX[i * subPer + s] = randNormal() * 12.5 * spreadMul
              baseOffY[i * subPer + s] = randNormal() * 12.5 * spreadMul
              sizeJitter[i * subPer + s] = 0.55 + rand() * 0.85
            }
          }
          simTime = 0
          /* neighbor-force scratch buffers, sized once per regenerate() (N is fixed
       until the next one) and reused every step() call instead of allocating
       6 fresh typed arrays every single physics step — this alone was showing
       up as measurable GC time in profiling */
          alignX = new Float64Array(N)
          alignY = new Float64Array(N)
          sepX = new Float64Array(N)
          sepY = new Float64Array(N)
          alignCount = new Int32Array(N)
          sepCount = new Int32Array(N)
        }
        // ---------------- state: background layer (sparse, weak, drifting, purely ambient) ----------------
        let bgN = 0
        let bgPos, bgVel, bgPhase, bgSize, bgGradU

        function regenerateBg() {
          bgN = Math.round(P.bgCount)
          bgPos = new Float64Array(bgN * 2)
          bgVel = new Float64Array(bgN * 2)
          bgPhase = new Float64Array(bgN)
          bgSize = new Float32Array(bgN)
          bgGradU = new Float64Array(bgN)
          for (let i = 0; i < bgN; i++) {
            bgPos[i * 2] = rand() * W
            bgPos[i * 2 + 1] = rand() * H
            bgVel[i * 2] = 0
            bgVel[i * 2 + 1] = 0
            bgPhase[i] = rand() * 50
            bgSize[i] = 0.55 + rand() * 0.9
            bgGradU[i] = rand() // no ribbon coordinate here, so just a persistent random gradient position
          }
        }
        // ---------------- simulation constants ----------------
        const neighborRadius = 46.0,
          neighborRadius2 = neighborRadius * neighborRadius
        const separationRadius = 14.0,
          separationRadius2 = separationRadius * separationRadius
        const maxForce = 0.1
        const HEADING_SPEED_MIN = 0.22 // below this, freeze the rendered heading instead of letting it spin on noise
        const cellSize = neighborRadius // grid cell for neighbor lookups (see buildGrid)
        // cursor: pulls while hovering, whether the cursor is moving or not -- but it
        // switches off inside an exclusion radius so particles don't pile up on top of it
        let mouseX = W / 2,
          mouseY = H / 2,
          mouseOver = false

        // autopilot: whenever there's no real cursor interaction, a virtual point roams
        // smoothly across the whole canvas on its own slow, organic path (a handful of
        // incommensurate low-frequency sine harmonics -- always continuous, never jumpy)
        // and pulls the flock the same way the cursor would. It runs on its own clock
        // (not simTime) so energy bursts/rests never make the roam itself feel jerky.
        let autoTime = 0
        /* --- Roam: a wandering point that sweeps the whole canvas in big curves at
     varying speed (steering-noise heading + a two-term speed oscillator),
     instead of the tight fixed-radius orbit autoPilotTarget makes. --- */
        let roamX = 0.5,
          roamY = 0.5,
          roamHeading = 2.1,
          roamT = 0
        function updateRoam(dt) {
          roamT += dt
          roamHeading +=
            Math.sin(roamT * 0.13 + 1.7) * 0.9 * dt +
            Math.sin(roamT * 0.057 + 4.1) * 0.5 * dt
          const speed =
            0.05 * (0.5 + 0.5 * Math.sin(roamT * 0.21 + 2.3)) +
            0.03 * (0.5 + 0.5 * Math.sin(roamT * 0.083 + 0.4))
          roamX += Math.cos(roamHeading) * speed * dt
          roamY += Math.sin(roamHeading) * speed * dt
          const m = 0.12
          if (roamX < m) {
            roamX = m
            roamHeading = Math.PI - roamHeading
          }
          if (roamX > 1 - m) {
            roamX = 1 - m
            roamHeading = Math.PI - roamHeading
          }
          if (roamY < m) {
            roamY = m
            roamHeading = -roamHeading
          }
          if (roamY > 1 - m) {
            roamY = 1 - m
            roamHeading = -roamHeading
          }
        }
        function autoPilotTarget(t, speed, phase) {
          const tt = t * speed
          const ux =
            0.5 +
            0.36 * Math.sin(tt * 0.35 + 0.6 + phase) +
            0.1 * Math.sin(tt * 0.12 + 2.1 + phase * 1.3) +
            0.06 * Math.sin(tt * 0.85 + 4.4 + phase * 0.7)
          const uy =
            0.5 +
            0.32 * Math.sin(tt * 0.24 + 2.7 + phase) +
            0.11 * Math.sin(tt * 0.58 + 0.3 + phase * 1.3) +
            0.05 * Math.sin(tt * 0.11 + 5.0 + phase * 0.7)
          return [clamp01(ux) * W, clamp01(uy) * H]
        }

        /* Neighbour grid as a counting sort: agents ordered by cell in one typed
     array, each cell a range of it. It used to be a Map of arrays rebuilt every
     step -- 5,000 pushes and a Map lookup per neighbouring cell per agent, and
     the garbage to go with them. Cells outside the frame are clamped onto the
     edge ones; that only adds comparisons the distance check throws out,
     since clamping never separates two neighbouring cells. */
        let gCols = 0,
          gRows = 0,
          cellStart = new Int32Array(0),
          cellOf = new Int32Array(0),
          order = new Int32Array(0)
        function buildGrid() {
          gCols = Math.ceil(W / cellSize) + 1
          gRows = Math.ceil(H / cellSize) + 1
          const nCells = gCols * gRows
          if (cellStart.length !== nCells + 1)
            cellStart = new Int32Array(nCells + 1)
          else cellStart.fill(0)
          if (cellOf.length !== N) {
            cellOf = new Int32Array(N)
            order = new Int32Array(N)
          }
          for (let i = 0; i < N; i++) {
            let cx = Math.floor(pos[i * 2] / cellSize),
              cy = Math.floor(pos[i * 2 + 1] / cellSize)
            cx = cx < 0 ? 0 : cx >= gCols ? gCols - 1 : cx
            cy = cy < 0 ? 0 : cy >= gRows ? gRows - 1 : cy
            const c = cy * gCols + cx
            cellOf[i] = c
            cellStart[c + 1]++
          }
          for (let c = 0; c < nCells; c++) cellStart[c + 1] += cellStart[c]
          const fillAt = cellStart.slice(0, nCells)
          for (let i = 0; i < N; i++) order[fillAt[cellOf[i]]++] = i
        }
        /* Every pair once: agent i against order[b0..b1), adding to both sides.
     Alignment is the other's velocity either way; separation is the same
     push, opposite sign. */
        function scanPairs(i, b0, b1) {
          const xi = pos[i * 2],
            yi = pos[i * 2 + 1],
            vxi = vel[i * 2],
            vyi = vel[i * 2 + 1]
          let aVX = 0,
            aVY = 0,
            aC = 0,
            sVX = 0,
            sVY = 0,
            sC = 0
          for (let b = b0; b < b1; b++) {
            const j = order[b]
            const dx = xi - pos[j * 2],
              dy = yi - pos[j * 2 + 1]
            const d2 = dx * dx + dy * dy
            if (d2 < neighborRadius2 && d2 > 1e-6) {
              aVX += vel[j * 2]
              aVY += vel[j * 2 + 1]
              aC++
              alignX[j] += vxi
              alignY[j] += vyi
              alignCount[j]++
              if (d2 < separationRadius2) {
                const d = Math.sqrt(d2)
                const w = (separationRadius - d) / separationRadius // stronger the closer they are
                const fx = (dx / d) * w,
                  fy = (dy / d) * w
                sVX += fx
                sVY += fy
                sC++
                sepX[j] -= fx
                sepY[j] -= fy
                sepCount[j]++
              }
            }
          }
          alignX[i] += aVX
          alignY[i] += aVY
          alignCount[i] += aC
          sepX[i] += sVX
          sepY[i] += sVY
          sepCount[i] += sC
        }

        function step(dt) {
          updateEnergy(dt)
          const eFactor = energyFactor()
          simTime += dt * P.speedMul * (0.7 + 0.3 * eFactor)
          const tm = simTime
          autoTime += dt

          // every force/damping constant below was originally tuned assuming a fixed ~60fps
          // step (dt ~= 1/60s) baked directly into the numbers -- so when the real frame
          // rate wobbles (a heavy particle count, a GC pause, a slow machine), the exact
          // same "per-step" impulse got applied over a longer or shorter real time slice,
          // which is what produced the jerky, stuttery, sometimes spinning-in-place motion.
          // dtFactor normalizes every one of those constants back to real elapsed time --
          // it's 1.0 exactly at 60fps (so the tuned look at 60fps is unchanged), and scales
          // proportionally at any other frame rate so the *real-time* motion stays identical
          // regardless of how choppy the actual rendering is. dt itself is already clamped
          // to 0.05s above (loop()), so dtFactor never exceeds 3 even after a big stutter.
          const dtFactor = dt * 60
          const velDamp = Math.pow(0.92, dtFactor)
          const bgVelDamp = Math.pow(0.95, dtFactor)
          const headBlend = Math.pow(0.82, dtFactor)

          /* Scaled, where it used to be raw: without this the attractor always took
       the same 5.3s to go round however fast the flock itself was set to move,
       so nothing could make them actually fly the path faster. */
          nullTime += dt * (P.pathSpeed != null ? P.pathSpeed : 1)

          const cursorExclude = P.cursorExclude
          // whichever point is "in charge" right now: the real cursor (if selected and actively
          // hovering), the keyframed "null" point (if selected and it has at least one keyframe),
          // or otherwise the roaming autopilot point -- so the flock always behaves as if
          // something were gently hovering over it, whatever the source
          const usingRealCursor = P.attractorSource === 'cursor' && mouseOver
          const nullPoint =
            P.attractorSource === 'null'
              ? floorPath(nullPositionAt(nullTime))
              : null
          const usingNull = !!nullPoint
          updateRoam(dt)
          let autoMainX, autoMainY, autoBgX, autoBgY
          if (P.motionMode === 'fixed') {
            autoMainX = P.anchorX * W
            autoMainY = P.anchorY * H
            autoBgX = autoMainX
            autoBgY = autoMainY
          } else if (P.motionMode === 'roam') {
            autoMainX = roamX * W
            autoMainY = roamY * H
            autoBgX = autoMainX
            autoBgY = autoMainY
          } else {
            ;[autoMainX, autoMainY] = autoPilotTarget(autoTime, P.autoSpeed, 0)
            ;[autoBgX, autoBgY] = autoPilotTarget(
              autoTime,
              P.autoSpeed * 0.82,
              13.7,
            )
          }
          const pointX = usingRealCursor
            ? mouseX
            : usingNull
              ? nullPoint.x * W
              : autoMainX
          const pointY = usingRealCursor
            ? mouseY
            : usingNull
              ? nullPoint.y * H
              : autoMainY
          const pointStrength =
            usingRealCursor || usingNull ? P.mouseStrength : P.autoWander
          // background layer gets its own, slightly de-synced roaming point so it doesn't
          // move in perfect lockstep with the main flock -- unless the cursor/null is in charge,
          // in which case it follows the same point as the main flock
          if (usingRealCursor || usingNull) {
            autoBgX = pointX
            autoBgY = pointY
          }

          // --- main flock: boids among agents, neighbors found via a spatial grid so
          // this stays fast with a lot more agents (no more full N x N scan) ---
          buildGrid()
          // (alignX/alignY/sepX/sepY/alignCount/sepCount are preallocated once in
          // regenerate(), zeroed here and summed into by scanPairs -- no realloc)
          alignX.fill(0)
          alignY.fill(0)
          alignCount.fill(0)
          sepX.fill(0)
          sepY.fill(0)
          sepCount.fill(0)
          /* Each cell against itself (later agents only) and four of its eight
       neighbours -- right, and the three below -- so every adjacent pair of
       cells is visited from exactly one side. */
          for (let cy = 0; cy < gRows; cy++) {
            for (let cx = 0; cx < gCols; cx++) {
              const c = cy * gCols + cx,
                c0 = cellStart[c],
                c1 = cellStart[c + 1]
              if (c0 === c1) continue
              const right = cx + 1 < gCols,
                down = cy + 1 < gRows,
                left = cx > 0
              for (let a = c0; a < c1; a++) {
                const i = order[a]
                scanPairs(i, a + 1, c1)
                if (right) scanPairs(i, cellStart[c + 1], cellStart[c + 2])
                if (down) {
                  const d = c + gCols
                  if (left) scanPairs(i, cellStart[d - 1], cellStart[d])
                  scanPairs(i, cellStart[d], cellStart[d + 1])
                  if (right) scanPairs(i, cellStart[d + 1], cellStart[d + 2])
                }
              }
            }
          }

          for (let i = 0; i < N; i++) {
            const t = tArr[i]
            const [gx, gy] = guideCurve(t, tm)
            const [tx, ty] = guideTangent(t, tm)
            const nx = -ty,
              ny = tx
            const ribbonX = (gx + nx * laneOffset[i]) * W
            const ribbonY = (gy + ny * laneOffset[i]) * H

            let ax = 0,
              ay = 0

            // follow ribbon target
            let fx = ribbonX - pos[i * 2],
              fy = ribbonY - pos[i * 2 + 1]
            let n = Math.hypot(fx, fy) + 1e-6
            const cap1 = Math.min(n, maxForce)
            ax += (fx / n) * cap1 * 1.4 * P.followStrength
            ay += (fy / n) * cap1 * 1.4 * P.followStrength

            // alignment -- skip when there's only a single neighbor: a mutual pair copying
            // each other's velocity is what causes those slow, endless little pirouettes
            if (alignCount[i] > 1) {
              let axn = alignX[i] / alignCount[i] - vel[i * 2]
              let ayn = alignY[i] / alignCount[i] - vel[i * 2 + 1]
              n = Math.hypot(axn, ayn) + 1e-6
              const cap2 = Math.min(n, maxForce)
              ax += (axn / n) * cap2 * 0.55
              ay += (ayn / n) * cap2 * 0.55
            }

            // separation
            if (sepCount[i] > 0) {
              let sxn = sepX[i] / sepCount[i],
                syn = sepY[i] / sepCount[i]
              n = Math.hypot(sxn, syn) + 1e-6
              const cap3 = Math.min(n, maxForce)
              ax += (sxn / n) * cap3 * 0.9 * P.sepStrength
              ay += (syn / n) * cap3 * 0.9 * P.sepStrength
            }

            // turbulence -- each agent has its own phase so neighbours don't get stuck
            // oscillating in lockstep with each other
            const [cx, cy] = curlNoise(
              tm + phaseOffset[i],
              pos[i * 2],
              pos[i * 2 + 1],
            )
            ax += cx
            ay += cy

            // pointer attraction: always on, sourced from the real cursor when the user is
            // hovering with attraction enabled, otherwise from the autopilot's roaming point --
            // switched off once a particle is already within the exclusion radius, so they
            // don't pile up on top of it
            {
              let mx = pointX - pos[i * 2],
                my = pointY - pos[i * 2 + 1]
              n = Math.hypot(mx, my) + 1e-6
              if (n > cursorExclude) {
                const cap4 = Math.min(n - cursorExclude, maxForce)
                ax += (mx / n) * cap4 * 1.2 * pointStrength
                ay += (my / n) * cap4 * 1.2 * pointStrength
              }
            }

            // the "capa media" layer reacts to every force above, but scaled down (or up)
            // by an adjustable multiplier -- a third, weaker-responding flocking layer
            if (layerCat[i] === CAT_MID) {
              ax *= P.midForce
              ay *= P.midForce
            }

            // normalize this step's impulse to real elapsed time (see dtFactor note above)
            ax *= dtFactor
            ay *= dtFactor

            vel[i * 2] = (vel[i * 2] + ax) * velDamp
            vel[i * 2 + 1] = (vel[i * 2 + 1] + ay) * velDamp
            const speed = Math.hypot(vel[i * 2], vel[i * 2 + 1]) + 1e-6
            const capS = Math.min(speed, P.maxSpeed * eFactor)
            vel[i * 2] = (vel[i * 2] / speed) * capS
            vel[i * 2 + 1] = (vel[i * 2 + 1] / speed) * capS
            pos[i * 2] += vel[i * 2] * dtFactor
            pos[i * 2 + 1] += vel[i * 2 + 1] * dtFactor

            // smoothed heading for rendering: freeze it while nearly stationary instead of
            // letting atan2() of a tiny, noisy vector spin the little particle cluster. The
            // blend itself is also normalized to real time (headBlend) so the smoothing
            // feels the same regardless of frame rate, instead of snapping harder on a slow
            // frame and barely turning at all on a fast one.
            if (capS > HEADING_SPEED_MIN) {
              const ndx = vel[i * 2] / capS,
                ndy = vel[i * 2 + 1] / capS
              let hx = headDirX[i] * headBlend + ndx * (1 - headBlend),
                hy = headDirY[i] * headBlend + ndy * (1 - headBlend)
              const hn = Math.hypot(hx, hy) + 1e-9
              headDirX[i] = hx / hn
              headDirY[i] = hy / hn
            }
          }

          // --- background layer: sparse, drifting, much weaker response, no mutual flocking ---
          const bgMaxSpeed = 1.05 * eFactor
          for (let i = 0; i < bgN; i++) {
            let ax = 0,
              ay = 0
            const [cx, cy] = curlNoise(
              tm * 0.75 + bgPhase[i],
              bgPos[i * 2],
              bgPos[i * 2 + 1],
            )
            ax += cx * 0.7 * P.bgForce
            ay += cy * 0.7 * P.bgForce

            {
              let mx = autoBgX - bgPos[i * 2],
                my = autoBgY - bgPos[i * 2 + 1]
              const n = Math.hypot(mx, my) + 1e-6
              if (n > cursorExclude) {
                const cap = Math.min(n - cursorExclude, maxForce * 0.7)
                ax += (mx / n) * cap * pointStrength * P.bgForce
                ay += (my / n) * cap * pointStrength * P.bgForce
              }
            }

            ax *= dtFactor
            ay *= dtFactor

            bgVel[i * 2] = (bgVel[i * 2] + ax) * bgVelDamp
            bgVel[i * 2 + 1] = (bgVel[i * 2 + 1] + ay) * bgVelDamp
            const speed = Math.hypot(bgVel[i * 2], bgVel[i * 2 + 1]) + 1e-6
            const capS = Math.min(speed, bgMaxSpeed)
            bgVel[i * 2] = (bgVel[i * 2] / speed) * capS
            bgVel[i * 2 + 1] = (bgVel[i * 2 + 1] / speed) * capS
            bgPos[i * 2] += bgVel[i * 2] * dtFactor
            bgPos[i * 2 + 1] += bgVel[i * 2 + 1] * dtFactor

            // wrap around the edges -- an ambient field has no hard boundary
            const m = 30
            if (bgPos[i * 2] < -m) bgPos[i * 2] += W + 2 * m
            if (bgPos[i * 2] > W + m) bgPos[i * 2] -= W + 2 * m
            if (bgPos[i * 2 + 1] < -m) bgPos[i * 2 + 1] += H + 2 * m
            if (bgPos[i * 2 + 1] > H + m) bgPos[i * 2 + 1] -= H + 2 * m
          }
        }
